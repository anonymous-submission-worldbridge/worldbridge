"""Source-level third residential district for ``urban_v1_full_09``.

The visible architecture is generated by the active ALL45-09 procedural
building functions in the same Blender process.  No completed residential
Blend is opened or appended.  The district retains ALL45-09's three low-rise
and eight high-rise dense-courtyard organization, facade language, spacing and
native-scale exterior dimensions, while reusing the five botanical tree
masters generated earlier in the full-city run.

The site is placed north of the two retained FULL07 residential areas.  A
pair of separated one-way community streets connects the existing y=65.5 m
street to the new east/west street without demolishing the retained houses or
apartments.  Markings, stop bars and pedestrian crossings are source geometry
and are audited here rather than painted into a saved scene.
"""
