# ─── REALIZER CLASS ───────────────────────────────────────────────────────────
class UrbanRealizer:
    def __init__(self, api_key=None, base_url=None, model_name=None):
        config = get_llm_config(default_model=model_name)
        self.config = config
        self.client = make_openai_client(config, api_key=api_key, base_url=base_url)
        self.model_name = model_name or config.model

    def synthesize_gin(self, params, manifest_data=None, user_prompt=None):
        """Build gin config for the flat/legacy path (deterministic + optional LLM review)."""
        base_gin = build_gin_from_params(params, manifest_data)

        manifest_str = json.dumps(manifest_data, indent=2) if manifest_data else "{}"
        params_str = json.dumps(params, indent=2)
        user_section = (
            f"\n### ORIGINAL USER PROMPT:\n{user_prompt}\n\n" if user_prompt else ""
        )

        system_prompt = f"""
You are the **Urban Scene Realizer** (Agent 3) for WorldBridge.
A deterministic compiler produced the base gin file below.
Review and optionally enrich it — add comments, fix logical issues.
DO NOT invent new gin parameter names, remove lines, or add markdown.

{user_section}### BASE GIN FILE:
{base_gin}

### RESOLVED PARAMETERS (reference):
{params_str}

### URBAN MANIFEST (context):
{manifest_str}

### OUTPUT:
Return ONLY the final .gin file content. No markdown, no code blocks.
"""
        try:
            content = complete_text(
                self.client,
                model=self.model_name,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {
                        "role": "user",
                        "content": "Output the final enriched urban .gin file.",
                    },
                ],
                temperature=0.05,
            )
            content = content.strip()
            if content.startswith("```gin") or content.startswith("```"):
                content = content.split("\n", 1)[1] if "\n" in content else content[3:]
            if content.endswith("```"):
                content = content[:-3]
            return content.strip()
        except Exception as e:
            print("API Error in Urban Realizer — falling back to deterministic gin:")
            print(describe_llm_exception(e))
            return base_gin


def save_gin(content, output_gin=OUTPUT_GIN, output_copy=OUTPUT_GIN_COPY):
    if not content:
        return False
    output_gin.parent.mkdir(parents=True, exist_ok=True)
    output_gin.write_text(content + "\n", encoding="utf-8")
    output_copy.parent.mkdir(parents=True, exist_ok=True)
    output_copy.write_text(content + "\n", encoding="utf-8")
    print(f"[Urban Realizer] Gin file saved to: {output_gin}")
    return True


