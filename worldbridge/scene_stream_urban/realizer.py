def _gen_park_tree(tag, tx, ty, C, seed=42, scale=1.0):
    print(f"[urban_pipeline] Tree {{tag}} at ({{tx:.1f}},{{ty:.1f}}) seed={{seed}} ...")
    cached = UA.place_infinigen_tree(tag, (tx, ty), C, tree_idx=seed % 5, scale=scale)
    if cached:
        print(f"[urban_pipeline] Tree {{tag}} done (prototype instance)")
        return cached[0]
    try:
        from infinigen.assets.objects.trees.generate import TreeFactory
        with FixedSeed(seed):
            fac = TreeFactory(seed=seed, season="summer", coarse=False, fruit_chance=0.0)
            root = fac.spawn_asset(0, loc=(tx, ty, 0), rot=(0, 0, 0))
        if root:
            if scale != 1.0:
                root.scale = (scale, scale, scale)
            UA.to_coll(root, C)
            for o in list(bpy.data.objects):
                if o != root and o.parent is root:
                    UA.to_coll(o, C)
            print(f"[urban_pipeline] Tree {{tag}} done (TreeFactory)")
        return root
    except Exception as _e:
        print(f"[urban_pipeline] TreeFactory fallback for {{tag}}: {{_e}}")
        rng=np.random.default_rng(seed)
        trunk_h=float(rng.uniform(4.6,6.1)*scale); trunk_r=float(rng.uniform(0.18,0.28)*scale)
        UA._cyl(f"{{tag}}_trunk",tx,ty,0.0,trunk_r,trunk_h,M["tree_trunk"],C,verts=14)
        for bi in range(6):
            a=bi/6.0*math.tau+float(rng.uniform(-0.22,0.22)); length=float(rng.uniform(1.4,2.4)*scale)
            z=trunk_h*float(rng.uniform(0.55,0.88)); bx_=tx+math.cos(a)*length*0.30; by_=ty+math.sin(a)*length*0.30
            br=UA._cyl(f"{{tag}}_br{{bi}}",bx_,by_,z,trunk_r*0.32,length,M["tree_trunk"],C,verts=8,rx=math.radians(62),rz=a)
            br.scale.x*=float(rng.uniform(0.75,1.10))
        for ci,(ox,oy,oz,rr) in enumerate([(0,0,1.05,2.5),(0.9,0.3,0.55,1.65),(-0.9,-0.2,0.50,1.65),(0.0,1.0,0.45,1.55),(0.1,-1.0,0.35,1.45),(0.0,0.0,1.75,1.55)]):
            jx=float(rng.uniform(-0.22,0.22)); jy=float(rng.uniform(-0.22,0.22))
            UA._sph(f"{{tag}}_can{{ci}}",tx+(ox+jx)*scale,ty+(oy+jy)*scale,trunk_h+oz*scale,rr*scale*float(rng.uniform(0.88,1.12)),M["tree_leaf"],C,segs=18,rings=12)
        print(f"[urban_pipeline] Tree {{tag}} done (fallback)")
        return None

