# ─── FLAT GIN BUILDER (legacy path) ──────────────────────────────────────────
def _fmt(value):
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f"{value}"
    return str(value)


def build_gin_from_params(params, manifest_data=None):
    lines = ["# Generated by Urban Realizer (WorldBridge)"]
    lines.append("\n# Block layout")
    for key in sorted(_COMPOSE_URBAN_PARAMS):
        if key in params:
            lines.append(f"{key} = {_fmt(params[key])}")
    lines.append("\n# Outdoor asset controls")
    for key in sorted(_OUTDOOR_ASSETS_PARAMS):
        if key in params:
            lines.append(f"{key} = {_fmt(params[key])}")
    lines.append("\n# Render and lighting")
    for key in sorted(_RENDER_PARAMS):
        if key in params:
            lines.append(f"{key} = {_fmt(params[key])}")
    if "atmosphere.fog_density" in params:
        fog = params["atmosphere.fog_density"]
        lines.append("\n# Atmosphere")
        lines.append(f"shader_atmosphere.density = {_fmt(fog)}")
        if fog > 0.005:
            lines.append("nishita_lighting.dust_density = 0.0")
    return "\n".join(lines)


